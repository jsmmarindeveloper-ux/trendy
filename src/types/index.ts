export type UserRole = 'admin' | 'editor';
export type RotationLevel = 'alta' | 'media' | 'baja';
export type MarginStatus = 'OK' | 'WARN' | 'DANGER';

export interface TenantConfig {
  nombre_tienda: string;
  margen_warn_pct: number;
  margen_danger_pct: number;
  catalogo_activo: boolean;
  whatsapp_contacto: string; // E.g. "573001234567"
  mensaje_bienvenida?: string;
  moneda?: string;
}

export interface Tenant {
  id: string;
  nombre: string;
  slug: string;
  activo: boolean;
  plan: 'free' | 'pro' | 'enterprise';
  creado_en?: any;
  config: TenantConfig;
}

export interface CompetitorProductCache {
  referencia: string; // SKU e.g. "DY2075"
  nombre: string;
  descripcion: string;
  imagen_url: string;
  precio_competidor: number;
  url_competidor: string;
  disponible: boolean;
  ultima_sync: any; // Firestore Timestamp
  sync_lock_until?: any; // Firestore Timestamp
}

export interface Producto {
  id: string; // docId: `${tenantId}_${productId}` or autogenerated
  tenant_id: string;
  referencia_competidor: string;
  nombre_personalizado: string;
  slug: string;
  precio_compra: number; // In COP
  precio_venta: number; // In COP
  stock: number;
  categoria: string;
  notas: string;
  visible_catalogo: boolean;
  analisis_ia?: string;
  rotacion_ia?: RotationLevel;
  imagen_override?: string;
  ultima_actualizacion?: any;
}

export interface TenantUsuario {
  id: string;
  tenant_id: string;
  uid: string;
  email: string;
  nombre: string;
  rol: UserRole;
  activo: boolean;
  creado_en?: any;
}

export interface TenantUsuarioPendiente {
  email: string;
  tenant_id: string;
  rol: UserRole;
}

export interface SuperAdminConfig {
  super_admin_uid: string;
  super_admin_email: string;
  created_at?: string;
}

export interface MarginCalculation {
  status: MarginStatus;
  marginPct: number; // vs competitor: ((precio_competidor - precio_compra) / precio_competidor) * 100
  profitOwnPct: number; // vs own price: ((precio_venta - precio_compra) / precio_venta) * 100
  profitCOP: number; // precio_venta - precio_compra
  priceDiffPct: number; // ((precio_venta - precio_competidor) / precio_competidor) * 100
  recommendation: string;
}

export interface AiAnalysisResult {
  rotacion: RotationLevel;
  resumen: string;
  tendencia: string;
  recomendacionPrecio: string;
}
